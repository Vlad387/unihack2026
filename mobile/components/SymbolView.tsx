// Iconițele pe care aplicația le știe desena și pe Android.
export type SymbolName = keyof typeof ANDROID_SYMBOLS;

type NativeName = SymbolViewProps['name'];
type Props = Omit<SymbolViewProps, 'name'> & {
  // Iconițele alese de utilizator sunt salvate ca text, deci `name` primește orice text, nu doar numele de mai sus.
  name: SymbolName | (string & {}) | Exclude<NativeName, string>;
};

export function SymbolView({ name, ...props }: Props) {
  if (Platform.OS !== 'android' || typeof name !== 'string') {
    return <NativeSymbolView name={name as NativeName} {...props} />;
  }
  return <NativeSymbolView name={{ android: (ANDROID_SYMBOLS as Record<string, AndroidSymbol | undefined>)[name] ?? 'radio_button_unchecked' }} {...props} />;
}
